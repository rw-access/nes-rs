import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { fixtureRom } from "./browser-fixture.mjs";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const base = process.env.NES_PREVIEW_URL || "http://127.0.0.1:8765/";
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium", headless: true, args: ["--no-sandbox", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
await mkdir("/tmp/nes-shared-check", { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 850 } });
  const errors = [], posts = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (request.method() === "POST") posts.push(request.url()); });
  await page.goto(base + "?debug=1");
  await page.waitForFunction(() => document.querySelector("#stage").dataset.ready === "true");
  await page.locator("#rom-input").setInputFiles({ name: "original-test.nes", mimeType: "application/octet-stream", buffer: fixtureRom() });
  await page.waitForFunction(() => BigInt(window.nesPlayerDebug().frame ?? 0) > 30n);
  const initial = await page.evaluate(() => window.nesPlayerDebug());
  assert.equal(await page.locator("#fps").isVisible(), false, "FPS starts hidden during normal play");
  await page.locator("#effects-settings-button").click();
  await page.locator("#show-fps-input").check(); await page.locator("#close-settings-button").click();
  assert.equal(await page.locator("#fps").isVisible(), true, "FPS is available on demand");
  await page.screenshot({ path: "/tmp/nes-shared-check/layered.png" });
  await page.locator("#more-button").click(); await page.locator("#play").click();
  const frozen = await page.evaluate(() => window.nesPlayerDebug());
  await page.locator("#snapshot-button").click();
  await page.locator("#orbit-button").click();
  await page.waitForFunction(() => window.nesPlayerDebug().mode === "orbit");
  assert.equal((await page.evaluate(() => window.nesPlayerDebug())).frame, frozen.frame);
  assert.equal((await page.evaluate(() => window.nesPlayerDebug())).emulatorId, initial.emulatorId);
  const rect = await page.locator("#stage").boundingBox();
  await page.mouse.move(rect.x + rect.width * .6, rect.y + rect.height * .5); await page.mouse.down(); await page.mouse.move(rect.x + rect.width * .8, rect.y + rect.height * .6); await page.mouse.up();
  await page.screenshot({ path: "/tmp/nes-shared-check/orbit.png" });
  await page.locator("#effects-button").click(); await page.waitForFunction(() => window.nesPlayerDebug().mode === "flat");
  assert.equal((await page.evaluate(() => window.nesPlayerDebug())).frame, frozen.frame);
  await page.screenshot({ path: "/tmp/nes-shared-check/flat.png" });
  await page.locator("#effects-settings-button").click();
  await page.waitForFunction(() => [...document.querySelectorAll(".look-card img")].every(img => img.complete && img.naturalWidth > 100));
  await page.screenshot({ path: "/tmp/nes-shared-check/settings.png" });
  await page.locator(".look-card").nth(1).click();
  assert.equal(await page.locator("#gap").inputValue(), "0");
  await page.locator("#save-defaults-button").click(); await page.locator("#close-settings-button").click();
  assert.equal((await page.evaluate(() => window.nesPlayerDebug())).frame, frozen.frame);
  await page.locator("#effects-button").click(); await page.waitForFunction(() => window.nesPlayerDebug().mode === "depth");
  await page.locator("#more-button").click(); await page.locator("#play").click();
  await page.waitForFunction(frame => BigInt(window.nesPlayerDebug().frame) > BigInt(frame) + 10n, frozen.frame);
  await page.locator("#more-button").click();
  await page.locator("#play").click();
  await page.locator("#restore-button").click();
  assert.equal(BigInt((await page.evaluate(() => window.nesPlayerDebug())).frame), BigInt(frozen.frame) + 1n);
  await page.locator("#play").click();
  await page.locator("#stage").focus(); await page.keyboard.down("ArrowRight");
  await page.waitForFunction(() => window.nesPlayerDebug().buttons === 128); await page.keyboard.up("ArrowRight");
  await page.waitForFunction(() => window.nesPlayerDebug().buttons === 0);
  await page.waitForFunction(frame => BigInt(window.nesPlayerDebug().frame) > BigInt(frame) + 25n, frozen.frame);
  const rewindAt = (await page.evaluate(() => window.nesPlayerDebug())).frame;
  await page.keyboard.down("r"); await page.waitForFunction(frame => BigInt(window.nesPlayerDebug().frame) < BigInt(frame) - 3n, rewindAt); await page.keyboard.up("r");
  await page.waitForFunction(() => !window.nesPlayerDebug().rewinding);
  // A bad replacement must preserve the running core and its state.
  await page.locator("#rom-input").setInputFiles({ name: "bad.nes", mimeType: "application/octet-stream", buffer: Buffer.from("bad") });
  await page.waitForFunction(() => document.querySelector("#status").textContent.includes("Could not load ROM"));
  assert.equal((await page.evaluate(() => window.nesPlayerDebug())).emulatorId, initial.emulatorId);
  assert.deepEqual(posts, []); assert.deepEqual(errors, []);
  console.log("Shared player transitions, frozen frame, saved state, keyboard, rewind, same-model previews, invalid ROM preservation and zero uploads passed");
} finally { await browser.close(); }
